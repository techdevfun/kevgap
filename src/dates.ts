/** Date helpers. All dates are plain UTC calendar days (YYYY-MM-DD). */

const DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;

export function isValidDate(value: string): boolean {
  const m = DATE_RE.exec(value);
  if (!m) return false;
  const y = Number(m[1]);
  const mo = Number(m[2]);
  const d = Number(m[3]);
  if (mo < 1 || mo > 12 || d < 1 || d > 31) return false;
  const dt = new Date(Date.UTC(y, mo - 1, d));
  return (
    dt.getUTCFullYear() === y &&
    dt.getUTCMonth() === mo - 1 &&
    dt.getUTCDate() === d
  );
}

export function parseDate(value: string): Date {
  const m = DATE_RE.exec(value);
  if (!m) throw new Error(`invalid date: ${value}`);
  const y = Number(m[1]);
  const mo = Number(m[2]);
  const d = Number(m[3]);
  const dt = new Date(Date.UTC(y, mo - 1, d));
  if (
    dt.getUTCFullYear() !== y ||
    dt.getUTCMonth() !== mo - 1 ||
    dt.getUTCDate() !== d
  ) {
    throw new Error(`invalid date: ${value}`);
  }
  return dt;
}

/** Whole days from `from` to `to` (to - from). Negative when to < from. */
export function daysBetween(from: string, to: string): number {
  const ms = parseDate(to).getTime() - parseDate(from).getTime();
  return Math.round(ms / 86_400_000);
}

export function addDays(date: string, days: number): string {
  const dt = parseDate(date);
  dt.setUTCDate(dt.getUTCDate() + days);
  return formatDate(dt);
}

export function formatDate(dt: Date): string {
  const y = dt.getUTCFullYear();
  const m = String(dt.getUTCMonth() + 1).padStart(2, "0");
  const d = String(dt.getUTCDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}

/**
 * Today's date (UTC). Tests and the demo may pin it with the
 * KEVGAP_TODAY environment variable; production runs always use the
 * real current date.
 */
export function todayString(): string {
  const pinned = process.env.KEVGAP_TODAY;
  if (pinned && isValidDate(pinned)) return pinned;
  return formatDate(new Date());
}
